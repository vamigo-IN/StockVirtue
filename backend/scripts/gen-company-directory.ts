/// Regenerates the offline company-name snapshots from NSE's official lists:
///   • backend/src/market/data/company-directory.snapshot.ts — boot fallback
///     for CompanyDirectoryService when NSE is unreachable.
///   • mobile/assets/data/company_names.json — bundled with the app so names
///     render on the very first frame, before /market/company-names answers.
///
/// Run from backend/:  npx ts-node scripts/gen-company-directory.ts
/// (The runtime service refreshes from NSE daily on its own; re-run this only
/// to refresh what ships offline.)
import * as fs from 'node:fs';
import * as path from 'node:path';
import axios from 'axios';
import {
  CompanyRecord,
  parseNseEquityList,
} from '../src/market/company-directory.parse';

const SOURCES = [
  {
    url: 'https://nsearchives.nseindia.com/content/equities/EQUITY_L.csv',
    sme: false,
  },
  {
    url: 'https://nsearchives.nseindia.com/emerge/corporates/content/SME_EQUITY_L.csv',
    sme: true,
  },
];

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
  '(KHTML, like Gecko) Chrome/130.0 Safari/537.36';

async function main() {
  const records: CompanyRecord[] = [];
  for (const src of SOURCES) {
    const { data } = await axios.get<string>(src.url, {
      timeout: 30_000,
      responseType: 'text',
      headers: { 'User-Agent': UA, Accept: 'text/csv,*/*' },
    });
    const parsed = parseNseEquityList(data, src.sme);
    if (parsed.length === 0) throw new Error(`No rows parsed from ${src.url}`);
    console.log(`${src.url}: ${parsed.length} companies`);
    records.push(...parsed);
  }
  // Mainboard wins over SME when a symbol appears in both (migrations).
  const bySymbol = new Map<string, CompanyRecord>();
  for (const r of records) {
    if (!bySymbol.has(r.symbol) || !r.sme) bySymbol.set(r.symbol, r);
  }
  const rows = [...bySymbol.values()].sort((a, b) =>
    a.symbol.localeCompare(b.symbol),
  );
  const today = new Date().toISOString().slice(0, 10);

  const backendOut = path.resolve(
    __dirname,
    '../src/market/data/company-directory.snapshot.ts',
  );
  const lines = rows.map(
    (r) =>
      `  [${JSON.stringify(r.symbol)}, ${JSON.stringify(r.name)}, ${JSON.stringify(r.listedOn ?? '')}, ${r.sme ? 1 : 0}],`,
  );
  fs.mkdirSync(path.dirname(backendOut), { recursive: true });
  fs.writeFileSync(
    backendOut,
    [
      '// AUTO-GENERATED by scripts/gen-company-directory.ts from NSE EQUITY_L.csv +',
      '// SME_EQUITY_L.csv. Do not edit by hand — re-run the script instead.',
      '/* eslint-disable */',
      `export const COMPANY_SNAPSHOT_DATE = '${today}';`,
      '',
      '/** [symbol, display name, listed on (YYYY-MM-DD or empty), 1 = SME] */',
      'export const COMPANY_SNAPSHOT: ReadonlyArray<',
      '  readonly [string, string, string, 0 | 1]',
      '> = [',
      ...lines,
      '];',
      '',
    ].join('\n'),
  );
  console.log(`wrote ${rows.length} rows → ${backendOut}`);

  const mobileOut = path.resolve(
    __dirname,
    '../../mobile/assets/data/company_names.json',
  );
  fs.mkdirSync(path.dirname(mobileOut), { recursive: true });
  const names: Record<string, string> = {};
  for (const r of rows) names[r.symbol] = r.name;
  fs.writeFileSync(
    mobileOut,
    JSON.stringify({ generatedAt: today, names }),
  );
  console.log(`wrote ${rows.length} names → ${mobileOut}`);
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
