/** A label's advance width in px. */
export function navLabelWidth(label: string): number {
  let w = 0;
  for (const ch of label) w += NAV_WIDTHS[ch] ?? NAV_FALLBACK_PX;
  return w;
}

/** The 768 px header's width for these labels: labels + 20 px each + 4 px between. */
export function navPrimaryWidth(labels: readonly string[]): number {
  const n = labels.length;
  return labels.reduce((s, l) => s + navLabelWidth(l), 0) + n * NAV_ITEM_PADDING_PX + Math.max(0, n - 1) * NAV_ITEM_GAP_PX;
}
